"""Stage 2 (Week 3): Train, Benchmark & Evaluate Classifiers on Concatenated CLIP Vectors.

Reads `features.csv` generated by `extract_features.py` (1024-dim OpenAI CLIP vectors),
trains and compares multiple classifiers per Stage 2 specification:
1. `MLPClassifier` (Hidden layers: `128 -> 64`, ReLU, L2 regularization)
2. `SVM_LinearKernel` (Linear Support Vector Machine with Platt probability calibration & balanced class weights)
3. `LGBMClassifier` (LightGBM Gradient Boosted Decision Trees with balanced class weights)
4. `MultimodalLinearL2` (Calibrated L2 Logistic/Neural Classifier supporting both 1024-d and 64-d)

Evaluates all models via Stratified Holdout & Cross-Validation, verifies Accuracy > 75% (BR-ML-03),
and exports both `.pkl` (`src/server/models/harmful_ad_classifier.pkl`) and `.json` weights.
"""

